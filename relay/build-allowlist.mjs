// Generates relay/src/allowlist.json, the only URLs the ahead-relay Worker will fetch, from the `viaRelay` sources in
// sources.config.mjs and the request headers in src/http.js. The Worker cannot import the registry (it ships without the
// pipeline), so the list is committed and tests/relay-allowlist.test.js fails when it is stale.
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { sources } from '../sources.config.mjs';
import { ACCEPT, ACCEPT_LANGUAGE, BROWSER_USER_AGENT } from '../src/http.js';
import { codePointCompare } from '../src/registry.js';

export const ALLOWLIST_NOTE = 'generated by relay/build-allowlist.mjs from sources.config.mjs and src/http.js; do not edit by hand';

/** `{ note, feeds: { id: url }, pages: { id: prefix }, headers }` with ids in code-point order (byte-deterministic output). */
export function buildAllowlist(list = sources) {
  const relayed = list.filter((s) => s.viaRelay === true).sort((a, b) => codePointCompare(a.id, b.id));
  const feeds = {};
  const pages = {};
  for (const s of relayed) {
    feeds[s.id] = s.url;
    if ('relayPagePrefix' in s) pages[s.id] = s.relayPagePrefix;
  }
  return {
    note: ALLOWLIST_NOTE,
    feeds,
    pages,
    // The pipeline's browser-like headers, so the Worker sends exactly what a direct fetch would (avoids drift, not required).
    headers: {
      'user-agent': BROWSER_USER_AGENT,
      'accept-language': ACCEPT_LANGUAGE,
      'accept-feed': ACCEPT.feed,
      'accept-html': ACCEPT.html,
    },
  };
}

const isMain = process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const allowlist = buildAllowlist();
  mkdirSync(new URL('./src/', import.meta.url), { recursive: true });
  writeFileSync(new URL('./src/allowlist.json', import.meta.url), `${JSON.stringify(allowlist, null, 2)}\n`);
  console.log(`relay/src/allowlist.json: ${Object.keys(allowlist.feeds).length} feeds, ${Object.keys(allowlist.pages).length} page prefixes`);
}
